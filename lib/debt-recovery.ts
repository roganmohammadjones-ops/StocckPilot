import { Linking, Share } from 'react-native';
import type { Customer } from './db/types';
import type { StoreProfile } from './store-profile';

/**
 * Formats a polite, firm, and authoritative debt recovery demand letter tailored for
 * Nigerian wholesale and retail markets (Idumota, Alaba, Balogun, Trade Fair, etc.)
 * with embedded settlement bank account details.
 */
export function generateDebtReminderMessage(
  customer: Customer,
  store: StoreProfile,
  customNote?: string
): string {
  const defaultBank =
    store.settlementAccounts?.find((a) => a.isDefault) || store.settlementAccounts?.[0];

  const bankDetails = defaultBank
    ? `🏦 *Bank:* ${defaultBank.bankName}\n🔢 *Account Number:* ${defaultBank.accountNumber}\n👤 *Account Name:* ${defaultBank.accountName}`
    : `🏦 *Payment:* Please visit our market depot or reply for current settlement account details.`;

  const cleanBalance = `₦${customer.balance.toLocaleString()}`;
  const statusNote =
    customer.debtStatus === 'overdue'
      ? `🚨 *STATUS: OVERDUE (${customer.dueText || 'Payment Overdue'})*`
      : `⏳ *Status:* Due Soon (${customer.dueText || 'Credit Terms Ending'})`;

  return (
    `*FORMAL DEMAND FOR SETTLEMENT OF OUTSTANDING ACCOUNT*\n` +
    `-----------------------------------------\n` +
    `*From:* ${store.businessName || 'StockPilot Merchant'}\n` +
    `*Location:* ${store.marketLocation || 'Lagos Market'}${store.marketStall ? `, ${store.marketStall}` : ''}\n` +
    (store.cacNumber ? `*CAC Reg:* ${store.cacNumber}\n` : '') +
    `-----------------------------------------\n\n` +
    `Dear *${customer.name}*,\n\n` +
    `This is a formal reminder regarding your outstanding trade credit balance with our depot.\n\n` +
    `• *Outstanding Amount:* *${cleanBalance}*\n` +
    `• *Terms:* ${statusNote}\n` +
    (customer.lastCredit ? `• *Last Credit Order:* ${customer.lastCredit}\n` : '') +
    (customer.lastPayment ? `• *Last Payment Credited:* ${customer.lastPayment}\n` : '') +
    (customNote && customNote.trim().length > 0 ? `\n*Manager's Note:* ${customNote.trim()}\n` : '') +
    `\nKindly transfer the full settlement to our verified account below:\n\n` +
    `${bankDetails}\n` +
    `📝 *Payment Reference:* DEBT-${customer.name.slice(0, 15).replace(/[^a-zA-Z0-9]/g, '')}\n\n` +
    `After payment, please reply with your transfer receipt slip so we can immediately clear your balance in our register.\n\n` +
    `Thank you for your prompt cooperation.\n` +
    `_${store.businessName || 'Store Management'} Accounts Team_`
  );
}

/**
 * Generates an aggregated audit summary of all overdue credit accounts for
 * market union reporting, internal debt tracking, or bulk broadcast.
 */
export function generateBatchDebtSummary(
  overdueCustomers: Customer[],
  store: StoreProfile
): string {
  const totalOverdue = overdueCustomers.reduce((sum, c) => sum + c.balance, 0);
  const defaultBank =
    store.settlementAccounts?.find((a) => a.isDefault) || store.settlementAccounts?.[0];

  const lines = overdueCustomers
    .map(
      (c, i) =>
        `${i + 1}. *${c.name}* (${c.phone})\n   • Owing: *₦${c.balance.toLocaleString()}* | ${c.dueText} | ${c.location}`
    )
    .join('\n\n');

  return (
    `📋 *OVERDUE DEBTOR AUDIT & RECOVERY SCHEDULE*\n` +
    `*Depot:* ${store.businessName} (${store.marketLocation})\n` +
    `*Audit Date:* ${new Date().toLocaleDateString('en-NG', { day: 'numeric', month: 'short', year: 'numeric' })}\n` +
    `*Total Overdue Receivables:* ₦${totalOverdue.toLocaleString()} across ${overdueCustomers.length} accounts\n` +
    `-----------------------------------------\n\n` +
    `${lines}\n\n` +
    `-----------------------------------------\n` +
    (defaultBank
      ? `Settlement Account: ${defaultBank.bankName} - ${defaultBank.accountNumber} (${defaultBank.accountName})\n`
      : '') +
    `Generated by StockPilot NG Debt Recovery Engine`
  );
}

/**
 * Dispatches the formatted debt reminder directly to the customer's WhatsApp chat.
 */
export function openDebtorWhatsApp(
  customer: Customer,
  store: StoreProfile,
  customNote?: string
): void {
  const cleanPhone = customer.phone.replace(/[^0-9]/g, '');
  const message = generateDebtReminderMessage(customer, store, customNote);
  const encoded = encodeURIComponent(message);
  Linking.openURL(`https://wa.me/${cleanPhone}?text=${encoded}`);
}

/**
 * Native share modal for sending debt demands via SMS, Email, or WhatsApp.
 */
export async function shareDebtorNotice(
  customer: Customer,
  store: StoreProfile,
  customNote?: string
): Promise<void> {
  const message = generateDebtReminderMessage(customer, store, customNote);
  await Share.share({
    title: `Payment Settlement Demand - ${customer.name}`,
    message,
  });
}

/**
 * Native share modal for the full batch overdue audit summary.
 */
export async function shareBatchOverdueSummary(
  overdueCustomers: Customer[],
  store: StoreProfile
): Promise<void> {
  const message = generateBatchDebtSummary(overdueCustomers, store);
  await Share.share({
    title: `StockPilot Overdue Debtors Schedule (${overdueCustomers.length} Accounts)`,
    message,
  });
}
